const fs = require('node:fs/promises');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const assert = require('node:assert/strict');
const arg = name => process.argv[process.argv.indexOf(name) + 1];
async function main() {
  const output = path.resolve(arg('--output')), api = arg('--api-url');
  assert.equal(new URL(api).port, '18767');
  await fs.mkdir(output, {recursive:true});
  const source = path.join(output,'source.mp4');
  execFileSync('ffmpeg',['-v','error','-f','lavfi','-i','color=c=blue:s=180x320:r=25','-f','lavfi','-i','sine=frequency=440','-t','6','-c:v','libx264','-c:a','aac',source]);
  execFileSync('ffmpeg',['-v','error','-i',source,'-frames:v','1',path.join(output,'cover.jpg')]);
  await fs.writeFile(path.join(output,'captions.srt'),'1\n00:00:00,000 --> 00:00:02,000\n这条裤子\n');
  const candidate = id => ({id,title:`测试成片${id}`,source_path:source,source_start_ms:0,source_end_ms:6000,video_path:'source.mp4',subtitle_path:'captions.srt',cover_path:'cover.jpg',hook:'测试',benchmark_refs:[],review_notes:[]});
  const manifest = path.join(output,'manifest.json');
  await fs.writeFile(manifest,JSON.stringify({schema_version:1,id:'management-qa',title:'文件管理验收',analysis_summary:'隔离测试',candidates:[candidate('one'),candidate('two')]}));
  const imported=await fetch(api+'/s7/footage-batches/import',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({manifest_path:manifest})});
  assert(imported.ok,await imported.text());
  const {chromium} = require(arg('--playwright-module'));
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const results=[], errors=[];
  try {
    const page=await browser.newPage({viewport:{width:1536,height:864}});
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(arg('--url'),{waitUntil:'networkidle'});
    await page.getByRole('button',{name:'视频剪辑',exact:true}).click();
    await page.getByRole('button',{name:'新建项目',exact:true}).click();
    await page.getByLabel('项目名称',{exact:true}).fill('项目删除恢复验收');
    const buffer=await fs.readFile(source);
    await page.locator('.auto-edit-create input[type=file]').setInputFiles([{name:'第一条.mp4',mimeType:'video/mp4',buffer},{name:'第二条.mp4',mimeType:'video/mp4',buffer}]);
    await page.getByRole('button',{name:'上移 第二条.mp4',exact:true}).click();
    assert((await page.locator('.selected-sources li').first().innerText()).includes('第二条.mp4'));
    const bounds=await Promise.all(['.auto-edit-source-panel','.auto-edit-settings-panel'].map(s=>page.locator(s).boundingBox()));
    assert(bounds[0].x<bounds[1].x,'upload on left, settings on right');
    for(const width of [2560,1920,1536,1280,800]) {
      await page.setViewportSize({width,height:900});
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
      await page.screenshot({path:path.join(output,`create-${width}.png`),fullPage:true});
    }
    await page.setViewportSize({width:1536,height:864});
    await page.route('**/s7/auto-edit-projects',route=>route.request().method()==='POST'?route.fulfill({status:503,json:{detail:'模拟保存失败'}}):route.continue());
    await page.getByRole('button',{name:'保存项目',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'模拟保存失败'}).waitFor();
    assert.equal(await page.getByLabel('项目名称',{exact:true}).inputValue(),'项目删除恢复验收');
    assert.equal(await page.locator('.selected-sources li').count(),2);
    await page.unroute('**/s7/auto-edit-projects');
    const created=page.waitForResponse(r=>r.url().endsWith('/s7/auto-edit-projects')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'保存项目',exact:true}).click();
    const project=await (await created).json();
    assert.deepEqual(project.sources.map(s=>s.file_name),['第二条.mp4','第一条.mp4']);
    await page.getByRole('button',{name:'删除项目',exact:true}).click();
    await page.getByRole('button',{name:'确认删除项目',exact:true}).click();
    await page.getByText('项目已移入回收站，已生成的成片和原始录播保留。',{exact:true}).waitFor();
    await page.reload({waitUntil:'networkidle'});
    assert.equal(await page.locator('.auto-edit-project-row').count(),0);
    await page.getByRole('button',{name:'项目回收站',exact:true}).click();
    await page.getByRole('button',{name:'恢复项目',exact:true}).click();
    await page.getByText('项目已恢复，可返回项目队列查看。',{exact:true}).waitFor();
    await page.getByRole('button',{name:'返回项目队列',exact:true}).click();
    await page.locator('.auto-edit-project-row').first().waitFor();
    const persisted=await (await fetch(api+'/s7/auto-edit-projects/'+project.project_id)).json();
    assert.equal(persisted.deleted_at,null);
    assert.equal(persisted.sources.length,2);
    results.push('双栏上传、顺序持久化、失败保留输入、项目删除刷新及恢复');
    await page.getByRole('button',{name:'成片素材库',exact:true}).click();
    const card=page.locator('.library-folder-card').filter({hasText:'文件管理验收'});
    await card.getByRole('button',{name:'重命名',exact:true}).click();
    await page.getByLabel('新名称',{exact:true}).fill('J85 上午第一批');
    await page.route('**/s7/library-management',route=>route.request().method()==='PATCH'?route.fulfill({status:503,json:{detail:'模拟整理失败'}}):route.continue());
    await page.getByRole('button',{name:'保存整理',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'模拟整理失败'}).waitFor();
    assert.equal(await page.getByLabel('新名称',{exact:true}).inputValue(),'J85 上午第一批');
    await page.unroute('**/s7/library-management');
    await page.getByRole('button',{name:'保存整理',exact:true}).click();
    await page.getByRole('button',{name:'打开批次 J85 上午第一批',exact:true}).waitFor();
    await page.locator('.library-folder-card').getByRole('button',{name:'分类',exact:true}).click();
    await page.getByLabel('分类名称（例如款号 J85）',{exact:true}).fill('J85');
    await page.getByRole('button',{name:'保存整理',exact:true}).click();
    await page.getByLabel('筛选分类',{exact:true}).selectOption('J85');
    await page.reload({waitUntil:'networkidle'});
    await page.getByRole('button',{name:'成片素材库',exact:true}).click();
    await page.getByRole('button',{name:'打开批次 J85 上午第一批',exact:true}).waitFor();
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('link',{name:'下载整批',exact:true}).click();
    const download=await downloadPromise;
    const downloaded=path.join(output,'batch.zip'); await download.saveAs(downloaded);
    execFileSync(path.resolve('.venv/Scripts/python.exe'),['-B','-c','import zipfile,sys; z=zipfile.ZipFile(sys.argv[1]); assert len([n for n in z.namelist() if n.endswith(".mp4")])==2; assert z.testzip() is None',downloaded]);
    await page.getByRole('button',{name:'打开批次 J85 上午第一批',exact:true}).click();
    await page.locator('.finished-item').first().getByRole('button',{name:'删除',exact:true}).click();
    await page.getByRole('button',{name:'确认移入回收站',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.finished-item').length===1);
    const exported=await fetch(api+'/local-exports',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({resource:'/s7/library-management/management-qa/archive'})});
    assert(exported.ok,await exported.clone().text());
    execFileSync(path.resolve('.venv/Scripts/python.exe'),['-B','-c','import zipfile,sys; z=zipfile.ZipFile(sys.argv[1]); assert len([n for n in z.namelist() if n.endswith(".mp4")])==1',(await exported.json()).path]);
    await page.getByRole('button',{name:'回收站',exact:true}).click();
    await page.getByRole('button',{name:'查看“J85 上午第一批”中删除的成片',exact:true}).click();
    await page.getByRole('button',{name:'恢复',exact:true}).click();
    await page.getByRole('button',{name:'返回成片库',exact:true}).click();
    await page.locator('.library-folder-card').getByRole('button',{name:'删除',exact:true}).click();
    await page.getByRole('button',{name:'确认移入回收站',exact:true}).click();
    await page.getByRole('button',{name:'回收站',exact:true}).click();
    await page.getByRole('button',{name:'恢复',exact:true}).click();
    await page.getByRole('button',{name:'返回成片库',exact:true}).click();
    await page.getByRole('button',{name:'打开批次 J85 上午第一批',exact:true}).waitFor();
    await page.screenshot({path:path.join(output,'library-managed.png'),fullPage:true});
    results.push('批次改名分类重开、失败保留输入、真实ZIP下载、文件删除过滤、文件及批次恢复');
    assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(output,'report.json'),JSON.stringify({results,errors},null,2));
    // Reuse the project's independent workspace acceptance against this isolated
    // persisted project. Its fixture name is historical, not a product rule.
    const updated=await (await fetch(api+'/s7/auto-edit-projects/'+project.project_id)).json();
    const renamed=await fetch(api+'/s7/auto-edit-projects/'+project.project_id,{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify({expected_revision:updated.revision,title:'0.1.24 真实剪辑验收',settings:updated.settings})});
    assert(renamed.ok);
    execFileSync(process.execPath,[path.resolve('scripts/verify-auto-edit-workspace.cjs'),'--url',arg('--url'),'--output',path.join(output,'workspace-regression'),'--playwright-module',arg('--playwright-module')],{stdio:'inherit'});
  } finally {await browser.close();}
}
main().catch(e=>{console.error(e);process.exit(1);});
